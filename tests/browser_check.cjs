const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[],network=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 await page.goto(pathToFileURL(path.resolve('dashboard/index.html')).href);
 await page.getByRole('heading',{name:'Known patterns. Unknown attacks.'}).waitFor();
 await page.screenshot({path:'results/dashboard-overview.png',fullPage:true});
 await page.locator('[data-tab="comparison"]').click();
 await page.locator('#metric').selectOption('auc');
 assert.equal(await page.locator('tbody tr').count(),5);
 await page.locator('[data-tab="unseen"]').click();
 await page.locator('#model').selectOption('gmm');
 await page.locator('[data-sort="recall"]').click();
 await page.screenshot({path:'results/dashboard-unseen.png',fullPage:true});
 await page.locator('[data-tab="cost"]').click();
 const before=await page.locator('#cost-output').innerText();
 await page.locator('#ratio').fill('2');await page.locator('#ratio').dispatchEvent('input');
 assert.notEqual(await page.locator('#cost-output').innerText(),before);
 await page.locator('#manual').check();
 await page.locator('#threshold').fill('1.0001');await page.locator('#threshold').dispatchEvent('input');
 assert.ok((await page.locator('#cost-output').innerText()).includes('1.0001'));
 await page.locator('#model').selectOption('rf');
 assert.ok((await page.locator('#cost-output').innerText()).includes('BAYES POSTERIOR REFERENCE'));
 await page.screenshot({path:'results/dashboard-cost.png',fullPage:true});
 await page.locator('[data-tab="feed"]').click();
 await page.locator('#seen').selectOption('0');
 await page.locator('[data-id]').first().click();
 assert.ok((await page.locator('#detail').innerText()).includes('Unseen'));
 await page.locator('#family').selectOption('U2R');
 await page.locator('#verdict').selectOption('attack');
 assert.ok((await page.locator('#content').innerText()).includes('matches'));
 assert.equal(await page.locator('footer a').getAttribute('href'),'https://zenodo.org/records/17424143');
 assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-tab="overview"]').click();
 await page.screenshot({path:'results/dashboard-mobile.png',fullPage:true});
 await browser.close();console.log('PASS: five tabs, selectors, cost controls, details, local-file loading, no network requests or browser errors.');
})().catch(e=>{console.error(e);process.exit(1);});
